import { randomUUID } from "node:crypto";
import type Database from "better-sqlite3";
import type { EmbeddingProvider } from "./embedding-provider.js";
import { KnowledgeServiceError, getKnowledgeDocument } from "./knowledge-service.js";
import { SqliteVectorStore } from "./vector-store.js";

export async function indexKnowledgeDocumentEmbeddings(
  db: Database.Database,
  projectId: string,
  documentId: string,
  provider: EmbeddingProvider
) {
  const document = getKnowledgeDocument(db, projectId, documentId) as {
    id: string;
    source_id: string;
    chunks: Array<{ id: string; content: string; content_hash: string }>;
  };
  if (document.chunks.length === 0) {
    throw new KnowledgeServiceError("EMBEDDING_DOCUMENT_EMPTY", 400, "Document has no chunks to embed.");
  }
  const store = new SqliteVectorStore(db);
  let indexed = 0;
  const batchSize = 32;
  for (let offset = 0; offset < document.chunks.length; offset += batchSize) {
    const batch = document.chunks.slice(offset, offset + batchSize);
    const result = await provider.embed(batch.map((chunk) => chunk.content));
    if (
      result.vectors.length !== batch.length ||
      result.model.dimensions !== provider.descriptor.dimensions ||
      result.vectors.some((vector) =>
        vector.length !== result.model.dimensions ||
        vector.some((value) => !Number.isFinite(value))
      )
    ) {
      throw new KnowledgeServiceError("EMBEDDING_PROVIDER_INVALID_OUTPUT", 502, "Embedding provider returned an invalid vector payload.");
    }
    const transaction = db.transaction(() => {
      for (let index = 0; index < batch.length; index += 1) {
        const chunk = batch[index];
        const vector = result.vectors[index];
        if (!chunk || !vector) continue;
        store.upsert({
          id: "ke_" + randomUUID().replaceAll("-", ""),
          project_id: projectId,
          source_id: document.source_id,
          document_id: document.id,
          chunk_id: chunk.id,
          content_hash: chunk.content_hash,
          provider: result.model.provider,
          model: result.model.model,
          model_version: result.model.modelVersion,
          dimensions: result.model.dimensions,
          simulated: result.model.simulated,
          semantic: result.model.semantic,
          vector
        });
        indexed += 1;
      }
    });
    transaction();
  }
  return {
    document_id: document.id,
    source_id: document.source_id,
    provider: provider.descriptor.provider,
    model: provider.descriptor.model,
    model_version: provider.descriptor.modelVersion,
    dimensions: provider.descriptor.dimensions,
    simulated: provider.descriptor.simulated,
    semantic: provider.descriptor.semantic,
    indexed_chunks: indexed,
    note: provider.descriptor.simulated
      ? "Synthetic mock vectors persisted for contract testing only; they do not encode semantic meaning."
      : "Embeddings generated by the configured provider."
  };
}

export function listKnowledgeDocumentEmbeddings(db: Database.Database, projectId: string, documentId: string) {
  getKnowledgeDocument(db, projectId, documentId);
  return new SqliteVectorStore(db).listByDocument(projectId, documentId);
}
